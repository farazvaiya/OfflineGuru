#!/usr/bin/env python3
"""Run one complete harness cycle in an isolated demo workspace.

This exercises the real orchestrator, database, state machine, benchmark engine,
independent evaluator and report generator, then stops at the mandatory human
decision gate. The problem used here is a *plumbing exercise*, not a claim about
Offline Guru quality: the numbers are synthetic and marked as such in the report.

Usage:
    python3 engineering_team/scripts/demo_cycle.py [--workspace PATH]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from engineering_team.harness import paths


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workspace", default=str(REPO / "engineering_team" / "state" / "demo"))
    ap.add_argument("--approve", choices=["A", "B", "HYBRID"], default=None,
                    help="Simulate the human decision so the integration gate can be exercised too")
    ap.add_argument("--keep", action="store_true",
                    help="Reuse the demo workspace instead of resetting it (default: reset)")
    args = ap.parse_args()

    team = Path(args.workspace)
    if team.exists() and not args.keep:
        # Only ever wipe a scratch demo workspace, never live harness state.
        if "demo" not in team.name:
            raise SystemExit(f"refusing to reset {team}: workspace name must contain 'demo'")
        shutil.rmtree(team)
    paths.TEAM_ROOT = team
    paths.DB_PATH = team / "state" / "engineering_team.db"
    paths.WORKFLOW_PATH = team / "state" / "workflow.json"
    paths.LOG_PATH = team / "logs" / "harness.log"
    paths.DECISION_REPORT_PATH = team / "reports" / "DECISION_REPORT.md"
    paths.INTEGRATION_REPORT_PATH = team / "reports" / "INTEGRATION_REPORT.md"
    paths.ensure_workspace()

    from engineering_team.harness.orchestrator import Orchestrator

    orch = Orchestrator()
    steps: list[dict[str, object]] = []

    def step(name: str, payload: object) -> None:
        steps.append({"step": name, "state": orch.state.state, "result": payload})
        print(f"[{orch.state.state}] {name}: {json.dumps(payload, default=str)[:200]}")

    step("initial status", orch.status())

    pid = orch.discover_problem(
        "DEMO (plumbing exercise): end-to-end workflow validation",
        "Synthetic problem record generated by engineering_team/scripts/demo_cycle.py to prove "
        "that discovery, dual-track records, benchmarks, independent evaluation, the decision "
        "report and the human approval gate work together. Not a real Offline Guru defect.",
        severity="P1",
        evidence=["engineering_team/scripts/demo_cycle.py"],
    )
    step("problem discovered", pid)

    orch.record_root_cause(
        pid,
        "DEMO root cause: none. This record exists only to exercise the workflow.",
        evidence=["engineering_team/scripts/demo_cycle.py"],
    )
    step("root cause recorded", "demo-only")

    orch.record_baseline(pid, {
        "note": "SYNTHETIC numbers for plumbing validation only; not measured.",
        "e2e_text_ms_p50": 1500, "e2e_text_ms_p95": 1880, "wer": 0.038,
    })
    step("baseline recorded", "synthetic")

    orch.start_dual_track()
    exp_a = orch.experiments.create(pid, "A", hypothesis="DEMO original approach (not implemented)")
    exp_b = orch.experiments.create(pid, "B", hypothesis="DEMO open-source approach (not implemented)")
    orch.experiments.record_implementation(exp_a, {"status": "demo stub", "files": []}, status="demo")
    orch.experiments.record_tests(exp_b, {"status": "demo stub", "tests": []}, status="demo")
    step("dual track experiments created", {"A": exp_a, "B": exp_b})

    bench = orch.record_benchmarks(
        pid,
        {
            "A": {"e2e_text_ms_p95": 1500, "wer": 0.038, "note": "SYNTHETIC"},
            "B": {"e2e_text_ms_p95": 1650, "wer": 0.039, "note": "SYNTHETIC"},
        },
        dataset="demo://synthetic-not-measured",
        config={"clients": 30, "mode": "simulated-plumbing-only"},
    )
    step("benchmarks recorded", bench)

    evaluation = orch.run_evaluation(pid, baseline={"e2e_text_ms_p95": 1880, "wer": 0.038})
    step("independent evaluation", {"id": evaluation["id"], "verdict": evaluation["verdict"],
                                    "limitations": evaluation["limitations"]})

    report = orch.prepare_decision_report(
        pid,
        recommendation=("DEMO ONLY: the harness plumbing recommends nothing. Replace the synthetic "
                        "records with measured evidence before any real decision."),
        uncertainties=[
            "All numbers in this demo are synthetic; no benchmark was executed.",
            "No implementation exists for Track A or Track B in this exercise.",
            "Physical classroom / microphone / hotspot validation was not performed.",
        ],
        benchmark={
            "methodology": {"note": "Not a benchmark: plumbing validation only."},
            "results": bench,
        },
        evaluation={"id": evaluation["id"], "verdict": evaluation["verdict"],
                    "limitations": evaluation["limitations"]},
    )
    step("decision report written", str(report))

    blocked = None
    try:
        orch.integrate_approved()
    except ValueError as exc:
        blocked = str(exc)
    step("integration refused before approval", blocked)

    if args.approve:
        step("human decision", orch.approve(args.approve))
        step("integration recorded", orch.integrate_approved(dry_run=True))
    else:
        step("awaiting human decision", "run `python3 -m engineering_team decisions` on the live workspace")

    persisted = orch.db.query("SELECT from_state, to_state, reason FROM workflow_events ORDER BY id")
    out = team / "reports" / "DEMO_RUN.json"
    out.write_text(json.dumps({"steps": steps, "workflow_events": persisted}, indent=2, default=str) + "\n",
                   encoding="utf-8")
    print(f"\nworkflow events: {len(persisted)}; transcript: {out}")
    print(f"final state: {orch.state.state}")
    orch.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
